//! `cargo xtask parity`: how closely the native engine agrees with Ghidra, as numbers.
//!
//! Runs `parity_report` of `crates/engine-native/tests/agreement.rs` (every binary of
//! `corpus/fixtures`, `corpus/pe/fixtures` and `corpus/elf32/fixtures` against the recorded Ghidra
//! results), joins the per-set sums with the rows of `parity.toml` (threshold and declared
//! status), writes `parity.json` and regenerates the marked section of
//! `docs/design/0014-native-engine.md`. The output holds no times or paths, so two runs on the
//! same tree give the same bytes. A row below its threshold, or whose declared status does not
//! match the measured value, fails the command.

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;
use std::process::Command;

use serde::Deserialize;
use serde_json::{Value, json};

use crate::{Result, workspace_root};

const BEGIN: &str = "<!-- parity:begin (generated by `cargo xtask parity`; do not edit) -->";
const END: &str = "<!-- parity:end -->";
/// Measured recall from which a row is at parity.
const PARITY_FROM: f64 = 0.95;
/// Measured recall below which a row counts as missing.
const MISSING_BELOW: f64 = 0.01;

#[derive(Debug, Deserialize)]
struct Table {
    row: Vec<Row>,
}

#[derive(Debug, Deserialize)]
struct Row {
    capability: String,
    set: String,
    format: String,
    threshold: f64,
    status: String,
    test: String,
}

pub fn parity(args: &[String]) -> Result<()> {
    let root = workspace_root();
    let toml_text = fs::read_to_string(root.join("parity.toml"))
        .map_err(|e| format!("cannot read parity.toml: {e}"))?;
    let table: Table = toml::from_str(&toml_text).map_err(|e| format!("parity.toml: {e}"))?;
    check_rows(&root, &table.row)?;

    let report: Value = match args {
        [flag, path] if flag == "--from" => serde_json::from_str(
            &fs::read_to_string(path).map_err(|e| format!("cannot read {path}: {e}"))?,
        )
        .map_err(|e| format!("{path}: {e}"))?,
        [] => run_report(&root)?,
        _ => return Err("usage: cargo xtask parity [--from <report.json>]".into()),
    };

    let mut rows = Vec::new();
    let mut failures = Vec::new();
    for r in &table.row {
        let m = &report[&r.set]["measures"][&r.capability];
        let Some(recall) = m["recall"].as_f64() else {
            return Err(format!("no measurement for {} on {}", r.capability, r.set));
        };
        let measured = if recall >= PARITY_FROM {
            "parity"
        } else if recall < MISSING_BELOW {
            "missing"
        } else {
            "partial"
        };
        let id = format!("{} on {}", r.capability, r.set);
        if recall < r.threshold {
            failures.push(format!(
                "{id}: recall {recall:.4} is below the threshold {}",
                r.threshold
            ));
        }
        if measured != r.status {
            failures.push(format!(
                "{id}: parity.toml says {}, the measurement says {measured} ({recall:.4})",
                r.status
            ));
        }
        rows.push(json!({
            "capability": r.capability,
            "set": r.set,
            "format": r.format,
            "recall": recall,
            "precision": m["precision"],
            "common": m["common"],
            "theirs": m["theirs"],
            "ours": m["ours"],
            "threshold": r.threshold,
            "status": r.status,
            "test": r.test,
        }));
    }
    let binaries: BTreeMap<&str, Value> = report
        .as_object()
        .into_iter()
        .flatten()
        .map(|(k, v)| (k.as_str(), v["binaries"].clone()))
        .collect();
    let out = json!({ "binaries": binaries, "rows": rows });
    let text = serde_json::to_string_pretty(&out).map_err(|e| e.to_string())? + "\n";
    fs::write(root.join("parity.json"), text)
        .map_err(|e| format!("cannot write parity.json: {e}"))?;
    write_adr(&root, &rows)?;
    println!("wrote parity.json and the parity section of docs/design/0014-native-engine.md");
    if failures.is_empty() {
        Ok(())
    } else {
        Err(failures.join("\n"))
    }
}

/// Every row names a test function that exists, a known capability and a known status.
fn check_rows(root: &Path, rows: &[Row]) -> Result<()> {
    let mut sources = String::new();
    let dir = root.join("crates/engine-native/tests");
    for e in fs::read_dir(&dir).map_err(|e| format!("{}: {e}", dir.display()))? {
        let p = e.map_err(|e| e.to_string())?.path();
        if p.extension().is_some_and(|x| x == "rs") {
            sources.push_str(&fs::read_to_string(&p).map_err(|e| e.to_string())?);
        }
    }
    for r in rows {
        if !sources.contains(&format!("fn {}(", r.test)) {
            return Err(format!(
                "parity.toml: row {} on {} names the test `{}`, which does not exist",
                r.capability, r.set, r.test
            ));
        }
        if !["parity", "partial", "missing"].contains(&r.status.as_str()) {
            return Err(format!("parity.toml: unknown status `{}`", r.status));
        }
        if !["corpus", "corpus/pe", "corpus/elf32"].contains(&r.set.as_str()) {
            return Err(format!("parity.toml: unknown set `{}`", r.set));
        }
    }
    Ok(())
}

fn run_report(root: &Path) -> Result<Value> {
    let out = std::env::temp_dir().join(format!("kraken-parity-{}.json", std::process::id()));
    let mut cmd = Command::new("cargo");
    cmd.current_dir(root)
        .args([
            "test",
            "-p",
            "engine-native",
            "--test",
            "agreement",
            "parity_report",
            "--",
            "--ignored",
            "--nocapture",
        ])
        .env("KRAKEN_PARITY_OUT", &out);
    if std::env::var_os("KRAKEN_NATIVE_SPECS").is_none()
        && let Some(home) = std::env::var_os("HOME")
    {
        let sla = Path::new(&home).join(".cache/kraken-dev/native-sla/Ghidra_12.2_build");
        if sla.is_dir() {
            cmd.env("KRAKEN_NATIVE_SPECS", sla);
        }
    }
    let status = cmd.status().map_err(|e| format!("cannot run cargo: {e}"))?;
    if !status.success() {
        return Err("the agreement test failed".into());
    }
    let text = fs::read_to_string(&out)
        .map_err(|_| "the agreement test wrote no report (no spec tree or decompiler build?)")?;
    let _ = fs::remove_file(&out);
    serde_json::from_str(&text).map_err(|e| e.to_string())
}

fn pct(v: &Value) -> String {
    v.as_f64()
        .map_or_else(|| "-".into(), |x| format!("{:.1}%", x * 100.0))
}

fn write_adr(root: &Path, rows: &[Value]) -> Result<()> {
    let mut sec = String::new();
    sec.push_str(BEGIN);
    sec.push_str(
        "\n\nRecall and precision against the Ghidra 12.2 fixtures (`parity.toml` holds the \
thresholds, `parity.json` the numbers). Decompile text is the share of Ghidra's words (comments \
left out) that the native text has, over the first 40 functions of each fixture; globals are \
auto-named data references; types and memory are compared by name and by extent; disassembly by \
address and mnemonic; jump tables by (jump, target) pair.\n\n",
    );
    sec.push_str("| Capability | Set | Format | Recall | Precision | Threshold | Status |\n");
    sec.push_str("|---|---|---|---|---|---|---|\n");
    for r in rows {
        sec.push_str(&format!(
            "| {} | `{}` | {} | {} | {} | {} | {} |\n",
            r["capability"].as_str().unwrap_or(""),
            r["set"].as_str().unwrap_or(""),
            r["format"].as_str().unwrap_or(""),
            pct(&r["recall"]),
            pct(&r["precision"]),
            pct(&r["threshold"]),
            r["status"].as_str().unwrap_or(""),
        ));
    }
    sec.push('\n');
    sec.push_str(END);
    let path = root.join("docs/design/0014-native-engine.md");
    let text = fs::read_to_string(&path).map_err(|e| format!("{}: {e}", path.display()))?;
    let (Some(a), Some(b)) = (text.find("<!-- parity:begin"), text.find(END)) else {
        return Err("docs/design/0014-native-engine.md has no parity markers".into());
    };
    let new = format!("{}{}{}", &text[..a], sec, &text[b + END.len()..]);
    if new != text {
        fs::write(&path, new).map_err(|e| e.to_string())?;
    }
    Ok(())
}
