#[cfg(test)]
mod tests {
    use super::*;
    use crate::ctypes::parse_prototype;

    #[test]
    fn every_entry_parses_and_names_are_unique() {
        let mut seen = std::collections::BTreeSet::new();
        for p in PROTOTYPES {
            let (name, _) = parse_prototype(p).unwrap_or_else(|e| panic!("{e}"));
            assert!(seen.insert(name.clone()), "{name} twice");
        }
        // the discovery list of functions that never return agrees with the table
        for n in crate::discover::NORETURN {
            if let Some(p) = PROTOTYPES
                .iter()
                .find(|p| parse_prototype(p).is_ok_and(|(m, _)| m == *n))
            {
                assert!(
                    p.starts_with("noreturn "),
                    "{n} returns according to the table"
                );
            }
        }
    }
}
