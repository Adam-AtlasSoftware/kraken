//! Deterministic CI mode: recorded engine fixtures, and scripted answers instead of a model.
//!
//! In CI nothing talks to a model or runs a decompiler. The tools run on `engine-fake` over the
//! corpus fixtures (recordings of a real Ghidra), and the answers come from a committed script
//! that a **stand-in** wrote: a deterministic rule that answers each task from the ground truth
//! and gets some of them wrong on purpose, so every kind of score, miss and unreadable answer is
//! exercised. The same script drives two backends:
//!
//! - as an [`EvalCassette`](crate::EvalCassette) through `ReplayProvider` (the API path), and
//! - as the answer file of the fake ACP agent (the terminal-agent path).
//!
//! A CI score therefore says the harness, the scoring and both backends work. It says nothing
//! about any model; use a live run for that.

