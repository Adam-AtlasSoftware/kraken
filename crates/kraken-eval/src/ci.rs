/// The committed answer script, generated by [`generate`].
pub const SCRIPT_JSON: &str = include_str!("../data/ci-script.json");
/// The committed cassette, generated by [`generate`].
pub const CASSETTE_JSON: &str = include_str!("../data/ci-cassette.json");
/// What the committed cassette says it was recorded with.
pub const STAND_IN: &str = "kraken-eval stand-in (scripted, not a model)";

/// One tool call a scripted answer makes first.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ScriptedTool {
    /// Command name.
    pub name: String,
    /// Arguments.
    pub arguments: Value,
}

/// A scripted answer to one task.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ScriptedTask {
    /// Tool calls made before answering.
    pub tools: Vec<ScriptedTool>,
    /// The final reply (usually ending in an answer block; a stand-in that gives up has none).
    pub answer: String,
}

/// Task id to scripted answer.
pub type Script = BTreeMap<String, ScriptedTask>;

/// The committed script.
pub fn committed_script() -> Result<Script, EvalError> {
    serde_json::from_str(SCRIPT_JSON)
        .map_err(|e| EvalError::Cassette(format!("ci-script.json: {e}")))
}

/// The committed cassette.
pub fn committed_cassette() -> Result<EvalCassette, EvalError> {
    EvalCassette::from_json(CASSETTE_JSON)
}

/// Writes the script to `path` as the fake ACP agent reads it.
pub fn write_script(script: &Script, path: &Path) -> Result<(), EvalError> {
    let mut text =
        serde_json::to_string_pretty(script).map_err(|e| EvalError::Cassette(e.to_string()))?;
    text.push('\n');
    std::fs::write(path, text).map_err(|e| EvalError::Cassette(format!("{}: {e}", path.display())))
}

fn answer_block(v: &Value) -> String {
    format!("{ANSWER_OPEN}{v}{ANSWER_CLOSE}")
}

fn hex(a: u64) -> String {
    format!("{a:#x}")
}

/// The stand-in's answer to `task`. `n` counts the tasks of the same kind before this one, so the
/// mistakes are spread out in a fixed pattern: every third function name is exact, one is half
/// right and one is wrong; every fourth function answer points at the wrong function; every other
/// set loses a member and gains a wrong one; the last text question gets no answer block.
pub fn stand_in(task: &ResolvedTask, n: usize, last: bool) -> ScriptedTask {
    match &task.expected {
        Expected::Names { functions } => {
            let mut names = serde_json::Map::new();
            for (j, f) in functions.iter().enumerate() {
                let name = match j % 3 {
                    0 => f.name.clone(),
                    1 => format!("{}_helper", f.name.split('_').next().unwrap_or("fn")),
                    _ => "handle_input".to_string(),
                };
                names.insert(hex(f.address), json!(name));
            }
            ScriptedTask {
                tools: functions
                    .iter()
                    .take(2)
                    .map(|f| ScriptedTool {
                        name: "decompile".into(),
                        arguments: json!({"address": hex(f.address)}),
                    })
                    .collect(),
                answer: format!(
                    "These are my best names after reading the code.\n{}",
                    answer_block(&json!({"names": names}))
                ),
            }
        }
        Expected::Function { start, size, .. } => {
            // Right: the function's entry. Wrong: the first byte after it, which is the next
            // function's neighbourhood (a model that looked one function too far).
            let right = n % 4 != 3;
            let address = if right { *start } else { start + size };
            ScriptedTask {
                tools: vec![ScriptedTool {
                    name: "decompile".into(),
                    arguments: json!({"address": hex(*start)}),
                }],
                answer: format!(
                    "This looks like the one.\n{}",
                    answer_block(&json!({"address": hex(address)}))
                ),
            }
        }
        Expected::YesNo { value } => {
            let said = if n % 2 == 1 { !value } else { *value };
            ScriptedTask {
                tools: vec![ScriptedTool {
                    name: "imports".into(),
                    arguments: json!({}),
                }],
                answer: format!(
                    "From the imports.\n{}",
                    answer_block(&json!({"answer": if said { "yes" } else { "no" }}))
                ),
            }
        }
        Expected::Set { items } => {
            let mut said = items.clone();
            if n % 2 == 1 {
                said.remove(0);
                said.push("puts".into());
            }
            ScriptedTask {
                tools: vec![ScriptedTool {
                    name: "imports".into(),
                    arguments: json!({"limit": 100}),
                }],
                answer: format!(
                    "The imports I could see.\n{}",
                    answer_block(&json!({"items": said}))
                ),
            }
        }
        Expected::Text { text } => {
            let tools = vec![ScriptedTool {
                name: "strings".into(),
                arguments: json!({"min_len": 6}),
            }];
            if last {
                ScriptedTask {
                    tools,
                    answer: "I could not find that string.".into(),
                }
            } else {
                ScriptedTask {
                    tools,
                    answer: format!(
                        "Found it among the strings.\n{}",
                        answer_block(&json!({"text": text.replace('\n', "\\n")}))
                    ),
                }
            }
        }
    }
}

/// Resolves every task of `suite` against the fixtures' image bases.
pub fn resolve_all(corpus: &Corpus, suite: &Suite) -> Result<Vec<ResolvedTask>, EvalError> {
    suite
        .tasks
        .iter()
        .map(|def| {
            let truth = corpus.truth(&def.binary)?;
            let base = corpus.fixture(&def.binary)?.program.base.0;
            def.resolve(&truth, base)
        })
        .collect()
}

/// The script the stand-in writes for `suite`.
pub fn generate_script(corpus: &Corpus, suite: &Suite) -> Result<Script, EvalError> {
    let tasks = resolve_all(corpus, suite)?;
    let mut counts: BTreeMap<&'static str, usize> = BTreeMap::new();
    let last_text = tasks
        .iter()
        .rposition(|t| matches!(t.expected, Expected::Text { .. }));
    let mut script = Script::new();
    for (i, t) in tasks.iter().enumerate() {
        let class = match t.expected {
            Expected::Names { .. } => "names",
            Expected::Function { .. } => "function",
            Expected::YesNo { .. } => "yes_no",
            Expected::Set { .. } => "set",
            Expected::Text { .. } => "text",
        };
        let n = counts.entry(class).or_default();
        script.insert(t.id.clone(), stand_in(t, *n, Some(i) == last_text));
        *n += 1;
    }
    Ok(script)
}

/// The cassette a script makes: for each task one response with its tool calls, then one with the
/// answer.
pub fn script_cassette(script: &Script) -> EvalCassette {
    let mut cassette = EvalCassette::new(STAND_IN);
    for (id, task) in script {
        let mut steps: Vec<Vec<StreamEvent>> = Vec::new();
        if !task.tools.is_empty() {
            let mut events: Vec<StreamEvent> = task
                .tools
                .iter()
                .enumerate()
                .map(|(i, t)| StreamEvent::ToolCallDelta {
                    index: i,
                    id: Some(format!("call_{i}")),
                    name: Some(t.name.clone()),
                    arguments: t.arguments.to_string(),
                })
                .collect();
            events.push(StreamEvent::Finish {
                reason: FinishReason::ToolCalls,
            });
            steps.push(events);
        }
        steps.push(vec![
            StreamEvent::TextDelta {
                text: task.answer.clone(),
            },
            StreamEvent::Finish {
                reason: FinishReason::Stop,
            },
        ]);
        cassette.tasks.insert(id.clone(), steps);
    }
    cassette
}

struct FixtureFactory {
    fixture: FixtureFile,
}

#[async_trait]
impl EngineFactory for FixtureFactory {
    async fn create(&self, _dir: &Path) -> Result<SharedEngine, ProtoError> {
        Ok(Arc::new(FakeEngine::new(self.fixture.clone())))
    }
}

/// Opens corpus binaries on `engine-fake` over the recorded fixtures: no decompiler, no
/// sidecar, the same answers every time.
pub struct FixtureEnvironment {
    corpus: Corpus,
    work: PathBuf,
    registry: Arc<Registry>,
}

impl FixtureEnvironment {
    /// An environment that keeps its projects under `work`.
    pub fn new(corpus: Corpus, work: PathBuf, registry: Arc<Registry>) -> Self {
        FixtureEnvironment {
            corpus,
            work,
            registry,
        }
    }
}

#[async_trait(?Send)]
impl Environment for FixtureEnvironment {
    fn describe(&self) -> String {
        "recorded fixtures (engine-fake)".to_string()
    }

    fn deterministic(&self) -> bool {
        true
    }

    async fn prepare(&self, binary: &str) -> Result<Prepared, EvalError> {
        let setup = |e: ProtoError| EvalError::Setup(format!("{binary}: {}", e.message));
        let fixture = self.corpus.fixture(binary)?;
        let base = fixture.program.base.0;
        let session = Arc::new(Session::new(Arc::new(FixtureFactory { fixture })));
        let dir = self.work.join("projects").join(binary);
        let exe = self.corpus.binary(binary);
        if dir.join("meta.json").exists() {
            session.open_project(&dir).await.map_err(setup)?;
        } else {
            session.create_project(&dir, &exe).await.map_err(setup)?;
        }
        let backend: Arc<dyn CommandBackend> =
            Arc::new(LocalBackend::new(self.registry.clone(), session, None));
        analyze(backend.as_ref()).await.map_err(setup)?;
        Ok(Prepared {
            binary: binary.to_string(),
            backend,
            project_dir: Some(dir),
            base,
        })
    }
}

/// Runs `analyze` and waits for it.
pub async fn analyze(backend: &dyn CommandBackend) -> Result<(), ProtoError> {
    let ctx = CallContext::user("kraken-eval", Surface::Cli);
    let job = backend.call("analyze", &ctx, json!({})).await?;
    let id = job["job_id"].clone();
    for _ in 0..40 {
        let done = backend
            .call(
                "job_await",
                &ctx,
                json!({"job_id": id, "timeout_ms": 30_000}),
            )
            .await?;
        match done["status"].as_str() {
            Some("running") => {}
            Some("succeeded") => return Ok(()),
            other => {
                return Err(ProtoError::new(
                    kraken_proto::ErrorCode::Internal,
                    format!("analysis ended as {}", other.unwrap_or("unknown")),
                ));
            }
        }
        tokio::time::sleep(Duration::from_millis(50)).await;
    }
    Err(ProtoError::new(
        kraken_proto::ErrorCode::Internal,
        "analysis did not finish",
    ))
}
