//! Preload mode of the strangler export: the accepted Rust functions run inside the original
//! Linux program.
//!
//! `rewrite_export` writes a library to link against. This module adds a third crate to that
//! workspace, `<name>-preload`, a shared library for `LD_PRELOAD`:
//!
//! - it exports every accepted function under its own name (calls through the dynamic symbol
//!   table reach the Rust version);
//! - when the program loads it, a constructor overwrites the entry of each accepted function in
//!   the running program with a 14-byte absolute jump to the Rust function (this is what reaches
//!   static functions and calls through function pointers);
//! - functions that are not accepted but that the Rust code calls are trampolines to the
//!   original's address in the running program;
//! - it tells the runtime shim where the program's data is, so functions that use globals see
//!   the real ones.
//!
//! The generated library is the model's code, so it is built in the sandbox like the export, and
//! [`check_run`] runs the original in the sandbox as well.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::time::Duration;

use crate::error::RewriteError;
use crate::export::{Manifest, cargo_build, io, shim_fn_with, write};
use crate::sandbox::{Confinement, ReadScope, confine, scratch_dir};

/// Bytes the entry jump overwrites.
pub const PATCH_LEN: u64 = 14;
/// Folder next to the workspace holding the built library and the launcher.
pub const OUT_DIR: &str = "preload";
/// File name of the launcher script.
pub const LAUNCHER: &str = "run-with-preload.sh";
/// Prefix of the lines the library writes to standard error with `KRAKEN_PRELOAD_LOG=1`.
pub const LOG_PREFIX: &str = "kraken-preload:";

const RUN_TIMEOUT: Duration = Duration::from_secs(60);
const OUTPUT_CAP: usize = 1 << 20;

/// What the library needs to know about the program.
#[derive(Debug, Clone)]
pub struct PreloadInput {
    /// The address the engine loaded the image at.
    pub image_base: u64,
    /// Size of the analysed file, to recognise the program at load time.
    pub binary_len: u64,
    /// Size of each function body by entry address (`0x...`), where the engine knows it.
    pub sizes: BTreeMap<String, u64>,
}

/// A function the library replaces.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Hook {
    /// The `extern "C"` name.
    pub symbol: String,
    /// Entry address as KRAKEN shows it.
    pub address: String,
    /// Body size.
    pub size: u64,
}

/// What [`write_preload`] decided.
#[derive(Debug, Clone)]
pub struct PreloadPlan {
    /// Crate name.
    pub crate_name: String,
    /// File name of the built library.
    pub library: String,
    /// Functions replaced.
    pub hooks: Vec<Hook>,
    /// Functions left in the original, with the reason.
    pub skipped: Vec<(String, String)>,
}

/// A built preload library.
#[derive(Debug, Clone)]
pub struct PreloadBuilt {
    /// The library.
    pub library: PathBuf,
    /// The launcher script.
    pub launcher: PathBuf,
    /// How the build was confined.
    pub sandbox: String,
}

fn hex(address: &str) -> Option<u64> {
    u64::from_str_radix(address.trim_start_matches("0x"), 16).ok()
}

/// Reads the manifest of the export in `dir`.
pub fn read_manifest(dir: &Path) -> Result<Manifest, RewriteError> {
    let text = std::fs::read_to_string(dir.join("manifest.json"))
        .map_err(|e| io(&dir.join("manifest.json").display().to_string(), e))?;
    let m: Manifest = serde_json::from_str(&text)
        .map_err(|e| RewriteError::Store(format!("manifest.json: {e}")))?;
    if m.generator != "kraken-rewrite" {
        return Err(RewriteError::Store(
            "manifest.json was not written by `rewrite_export`".into(),
        ));
    }
    Ok(m)
}

/// Refuses a file that is not a 64-bit x86 ELF program.
pub fn require_x86_64_elf(binary: &Path) -> Result<(), RewriteError> {
    use object::read::elf::ElfFile64;
    use object::{Architecture, Object};
    let data = std::fs::read(binary).map_err(|e| io(&binary.display().to_string(), e))?;
    let file = ElfFile64::<object::Endianness>::parse(&*data)
        .map_err(|_| RewriteError::Unsupported("preload mode needs a 64-bit ELF program".into()))?;
    if file.architecture() != Architecture::X86_64 {
        return Err(RewriteError::Unsupported(
            "preload mode is implemented for x86-64 programs only".into(),
        ));
    }
    Ok(())
}

const TEMPLATE: &str = r#"//! Preload library generated by KRAKEN: puts the Rust versions of accepted functions into the
//! running original program. See the README of the export.
#![allow(warnings)]

use std::ffi::{c_int, c_void};
use std::sync::atomic::{AtomicU64, AtomicUsize, Ordering::Relaxed};

const IMAGE_BASE: u64 = @IMAGE_BASE@;
const EXPECT_LEN: u64 = @EXPECT_LEN@;
const NAMES: [&str; @N@] = [@NAMES@];
const HOOKS: [(u64, u64); @N@] = [@HOOKS@];
const TRAMPOLINES: [u64; @M@] = [@TRAMPOLINES@];
static COUNTS: [AtomicU64; @N@] = [const { AtomicU64::new(0) }; @N@];
static ORIG: [AtomicUsize; @M@] = [const { AtomicUsize::new(0) }; @M@];
static INSTALLED: AtomicUsize = AtomicUsize::new(0);

@WRAPPERS@
fn hook_fns() -> [usize; @N@] {
    [@FNS@]
}

@TRAMPOLINE_ASM@

#[repr(C)]
struct DlInfo {
    addr: usize,
    name: *const u8,
    phdr: *const Phdr,
    phnum: u16,
}

#[repr(C)]
struct Phdr {
    p_type: u32,
    p_flags: u32,
    p_offset: u64,
    p_vaddr: u64,
    p_paddr: u64,
    p_filesz: u64,
    p_memsz: u64,
    p_align: u64,
}

struct Main {
    bias: usize,
    lo: u64,
    hi: u64,
}

unsafe extern "C" {
    fn dl_iterate_phdr(
        cb: unsafe extern "C" fn(*mut DlInfo, usize, *mut c_void) -> c_int,
        data: *mut c_void,
    ) -> c_int;
    fn mprotect(addr: *mut c_void, len: usize, prot: c_int) -> c_int;
    fn sysconf(name: c_int) -> i64;
}

unsafe extern "C" fn first(info: *mut DlInfo, _size: usize, data: *mut c_void) -> c_int {
    let m = unsafe { &mut *(data as *mut Main) };
    let info = unsafe { &*info };
    m.bias = info.addr;
    for i in 0..info.phnum as usize {
        let p = unsafe { &*info.phdr.add(i) };
        if p.p_type == 1 {
            m.lo = m.lo.min(p.p_vaddr & !0xfff);
            m.hi = m.hi.max(p.p_vaddr + p.p_memsz);
        }
    }
    1
}

fn truthy(name: &str) -> bool {
    std::env::var_os(name).is_some_and(|v| !v.is_empty() && v != "0")
}

unsafe fn patch(target: usize, to: usize) -> bool {
    let page = (unsafe { sysconf(30) }).max(4096) as usize;
    let start = target & !(page - 1);
    let end = (target + @PATCH_LEN@ + page - 1) & !(page - 1);
    if unsafe { mprotect(start as *mut c_void, end - start, 7) } != 0 {
        return false;
    }
    let mut bytes = [0u8; @PATCH_LEN@];
    bytes[..6].copy_from_slice(&[0xff, 0x25, 0, 0, 0, 0]);
    bytes[6..].copy_from_slice(&(to as u64).to_le_bytes());
    unsafe { std::ptr::copy_nonoverlapping(bytes.as_ptr(), target as *mut u8, @PATCH_LEN@) };
    unsafe { mprotect(start as *mut c_void, end - start, 5) };
    true
}

extern "C" fn init() {
    if truthy("KRAKEN_PRELOAD_DISABLE") {
        return;
    }
    let mut m = Main { bias: 0, lo: u64::MAX, hi: 0 };
    unsafe { dl_iterate_phdr(first, &mut m as *mut Main as *mut c_void) };
    if m.lo == u64::MAX {
        return;
    }
    let len = std::fs::metadata("/proc/self/exe").map(|x| x.len()).unwrap_or(0);
    if len != EXPECT_LEN {
        eprintln!(
            "@LOG@ not replacing anything: this program is {len} bytes, the library was built \
             for one of {EXPECT_LEN} bytes"
        );
        return;
    }
    let at = (m.bias as u64).wrapping_add(m.lo);
    @LIB@::rt::image_attach(at as *mut u8, IMAGE_BASE, (m.hi - m.lo) as usize);
    let runtime = |a: u64| at.wrapping_add(a.wrapping_sub(IMAGE_BASE));
    for i in 0..TRAMPOLINES.len() {
        ORIG[i].store(runtime(TRAMPOLINES[i]) as usize, Relaxed);
    }
    let fns = hook_fns();
    for (i, (addr, size)) in HOOKS.iter().enumerate() {
        let target = runtime(*addr);
        if target < at || target + size > at + (m.hi - m.lo) {
            eprintln!("@LOG@ {} is outside the program image; left alone", NAMES[i]);
            continue;
        }
        if unsafe { patch(target as usize, fns[i]) } {
            INSTALLED.fetch_add(1, Relaxed);
        } else {
            eprintln!("@LOG@ cannot make the code of {} writable; left alone", NAMES[i]);
        }
    }
    if truthy("KRAKEN_PRELOAD_LOG") {
        eprintln!("@LOG@ replaced {} of {} functions", INSTALLED.load(Relaxed), HOOKS.len());
    }
}

extern "C" fn fini() {
    if truthy("KRAKEN_PRELOAD_LOG") && INSTALLED.load(Relaxed) > 0 {
        for i in 0..NAMES.len() {
            eprintln!("@LOG@ calls {}={}", NAMES[i], COUNTS[i].load(Relaxed));
        }
    }
}

#[used]
#[unsafe(link_section = ".init_array")]
static INIT: extern "C" fn() = init;

#[used]
#[unsafe(link_section = ".fini_array")]
static FINI: extern "C" fn() = fini;
"#;

/// Writes the preload crate into the export in `dir` and adds it to the workspace.
pub fn write_preload(dir: &Path, input: &PreloadInput) -> Result<PreloadPlan, RewriteError> {
    let m = read_manifest(dir)?;
    let prefix = m
        .lib_crate
        .strip_suffix("-rewrite")
        .unwrap_or(&m.lib_crate)
        .to_string();
    let crate_name = format!("{prefix}-preload");
    let lib_ident = m.lib_crate.replace('-', "_");
    let mut hooks = Vec::new();
    let mut skipped = Vec::new();
    let mut wrappers = String::new();
    let mut fns = Vec::new();
    for e in &m.exports {
        let Some(addr) = hex(&e.address) else {
            skipped.push((e.symbol.clone(), format!("bad address {}", e.address)));
            continue;
        };
        let Some(sig) = &e.signature else {
            skipped.push((
                e.symbol.clone(),
                "the export is older than preload mode; export again".into(),
            ));
            continue;
        };
        let Some(&size) = input.sizes.get(&e.address) else {
            skipped.push((
                e.symbol.clone(),
                "the size of the function is unknown".into(),
            ));
            continue;
        };
        if size < PATCH_LEN {
            skipped.push((
                e.symbol.clone(),
                format!("the function is {size} bytes, shorter than the {PATCH_LEN}-byte jump"),
            ));
            continue;
        }
        let i = hooks.len();
        wrappers.push_str(&shim_fn_with(
            sig,
            &format!("{lib_ident}::u_{0}::{0}", e.symbol),
            &format!("COUNTS[{i}].fetch_add(1, Relaxed);\n    "),
        ));
        wrappers.push('\n');
        fns.push(e.symbol.clone());
        hooks.push(Hook {
            symbol: e.symbol.clone(),
            address: e.address.clone(),
            size,
        });
        let _ = addr;
    }
    if hooks.is_empty() {
        let why = skipped
            .iter()
            .map(|(s, r)| format!("{s}: {r}"))
            .collect::<Vec<_>>()
            .join("; ");
        return Err(RewriteError::Store(format!(
            "no accepted function can be replaced in the running program ({why})"
        )));
    }
    let mut trampolines: Vec<(String, u64)> = Vec::new();
    for c in &m.calls_original {
        if let (Some(name), Some(addr)) = (&c.link_name, hex(&c.address))
            && !trampolines.iter().any(|(n, _)| n == name)
        {
            trampolines.push((name.clone(), addr));
        }
    }
    let asm = if trampolines.is_empty() {
        String::new()
    } else {
        let mut text = String::from(".pushsection .text\\n.p2align 4\\n");
        for (i, (name, _)) in trampolines.iter().enumerate() {
            text.push_str(&format!(
                ".globl {name}\\n.hidden {name}\\n.type {name},@function\\n{name}:\\n\
                 jmp *{{orig}}+{off}(%rip)\\n.size {name},.-{name}\\n",
                off = i * 8
            ));
        }
        text.push_str(".popsection\\n");
        format!(
            "// Calls to functions that are not rewritten go to the original in the program.\n\
             std::arch::global_asm!(\"{text}\", orig = sym ORIG, options(att_syntax));\n"
        )
    };
    let quote = |s: &str| format!("{s:?}");
    let code = TEMPLATE
        .replace("@IMAGE_BASE@", &format!("{:#x}", input.image_base))
        .replace("@EXPECT_LEN@", &input.binary_len.to_string())
        .replace("@N@", &hooks.len().to_string())
        .replace("@M@", &trampolines.len().to_string())
        .replace(
            "@NAMES@",
            &hooks
                .iter()
                .map(|h| quote(&h.symbol))
                .collect::<Vec<_>>()
                .join(", "),
        )
        .replace(
            "@HOOKS@",
            &hooks
                .iter()
                .map(|h| format!("({}, {})", hex(&h.address).unwrap_or(0), h.size))
                .collect::<Vec<_>>()
                .join(", "),
        )
        .replace(
            "@TRAMPOLINES@",
            &trampolines
                .iter()
                .map(|(_, a)| a.to_string())
                .collect::<Vec<_>>()
                .join(", "),
        )
        .replace("@WRAPPERS@", &wrappers)
        .replace(
            "@FNS@",
            &fns.iter()
                .map(|f| format!("{f} as usize"))
                .collect::<Vec<_>>()
                .join(", "),
        )
        .replace("@TRAMPOLINE_ASM@", &asm)
        .replace("@PATCH_LEN@", &PATCH_LEN.to_string())
        .replace("@LOG@", LOG_PREFIX)
        .replace("@LIB@", &lib_ident);
    let ident = crate_name.replace('-', "_");
    write(&dir.join(&crate_name).join("src/lib.rs"), &code)?;
    write(
        &dir.join(&crate_name).join("Cargo.toml"),
        &format!(
            "[package]\nname = \"{crate_name}\"\nversion = \"0.1.0\"\nedition = \"2024\"\n\
             publish = false\ndescription = \"LD_PRELOAD library running the rewrites of {lib} \
             inside the original program\"\n\n\
             [lib]\nname = \"{ident}\"\npath = \"src/lib.rs\"\ncrate-type = [\"cdylib\"]\n\n\
             [dependencies]\n{lib} = {{ path = \"../{lib}\" }}\n",
            lib = m.lib_crate
        ),
    )?;
    write(
        &dir.join("Cargo.toml"),
        &format!(
            "[workspace]\nmembers = [\"{}\", \"{}\", \"{crate_name}\"]\nresolver = \"2\"\n",
            m.lib_crate, m.ffi_crate
        ),
    )?;
    Ok(PreloadPlan {
        library: format!("lib{ident}.so"),
        crate_name,
        hooks,
        skipped,
    })
}

fn launcher_text(library: &str) -> String {
    format!(
        "#!/bin/sh\n\
         # Runs PROGRAM with the Rust versions of the accepted functions loaded into it.\n\
         # Usage: {LAUNCHER} PROGRAM [ARGS...]\n\
         # KRAKEN_PRELOAD_DISABLE=1 turns the library off, KRAKEN_PRELOAD_LOG=1 reports on stderr.\n\
         here=$(CDPATH= cd -- \"$(dirname -- \"$0\")\" && pwd)\n\
         LD_PRELOAD=\"$here/{library}${{LD_PRELOAD:+:$LD_PRELOAD}}\" exec \"$@\"\n"
    )
}

/// Builds the workspace of `dir` in the sandbox and copies the library and the launcher into
/// `<dir>/preload/`.
pub fn build_preload(
    dir: &Path,
    plan: &PreloadPlan,
    confinement: &Confinement,
) -> Result<PreloadBuilt, RewriteError> {
    let b = cargo_build(dir, confinement, "the preload library")?;
    let built = b.target.join("release").join(&plan.library);
    let out = dir.join(OUT_DIR);
    std::fs::create_dir_all(&out).map_err(|e| io(&out.display().to_string(), e))?;
    let library = out.join(&plan.library);
    std::fs::copy(&built, &library).map_err(|e| io(&built.display().to_string(), e))?;
    let launcher = out.join(LAUNCHER);
    write(&launcher, &launcher_text(&plan.library))?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(&launcher, std::fs::Permissions::from_mode(0o755))
            .map_err(|e| io(&launcher.display().to_string(), e))?;
    }
    Ok(PreloadBuilt {
        library,
        launcher,
        sandbox: b.sandbox,
    })
}

/// One run of the original.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RunOutcome {
    /// `exit N`, `signal N` or `timeout`.
    pub exit: String,
    /// Standard output.
    pub stdout: Vec<u8>,
    /// Standard error, without the library's own lines.
    pub stderr: Vec<u8>,
    /// Calls per function reported by the library.
    pub calls: Vec<(String, u64)>,
}

/// The original and the preloaded run side by side.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PreloadComparison {
    /// The run without the library.
    pub original: RunOutcome,
    /// The run with it.
    pub preloaded: RunOutcome,
}

impl PreloadComparison {
    /// True when exit, standard output and standard error agree.
    pub fn identical(&self) -> bool {
        self.original.exit == self.preloaded.exit
            && self.original.stdout == self.preloaded.stdout
            && self.original.stderr == self.preloaded.stderr
    }

    /// A short description of the first difference.
    pub fn difference(&self) -> Option<String> {
        if self.identical() {
            return None;
        }
        let (a, b) = (&self.original, &self.preloaded);
        let cut = |v: &[u8]| String::from_utf8_lossy(&v[..v.len().min(300)]).into_owned();
        Some(if a.exit != b.exit {
            format!("exit: original {}, preloaded {}", a.exit, b.exit)
        } else if a.stdout != b.stdout {
            format!(
                "stdout differs: original {:?}, preloaded {:?}",
                cut(&a.stdout),
                cut(&b.stdout)
            )
        } else {
            format!(
                "stderr differs: original {:?}, preloaded {:?}",
                cut(&a.stderr),
                cut(&b.stderr)
            )
        })
    }
}

fn run_one(
    binary: &Path,
    library: Option<&Path>,
    args: &[String],
    stdin: Option<&str>,
    confinement: &Confinement,
) -> Result<RunOutcome, RewriteError> {
    let scratch = scratch_dir("kraken-preload-run-")?;
    let mut opts = confinement.clone();
    opts.extra_read_paths.push(binary.to_path_buf());
    if let Some(l) = library {
        opts.extra_read_paths.push(l.to_path_buf());
    }
    let mut cmd = Command::new(binary);
    cmd.args(args);
    confine(&mut cmd, scratch.path(), ReadScope::SystemLibraries, &opts)?;
    if let Some(l) = library {
        cmd.env("LD_PRELOAD", l).env("KRAKEN_PRELOAD_LOG", "1");
    }
    let out = crate::sandbox::run_captured_with_input(
        &mut cmd,
        stdin.map(|t| t.as_bytes().to_vec()),
        RUN_TIMEOUT,
        OUTPUT_CAP,
        Duration::from_millis(20),
    )
    .map_err(|e| RewriteError::Native(format!("cannot run {}: {e}", binary.display())))?;
    let exit = match out.status {
        None => "timeout".to_string(),
        Some(s) => match s.code() {
            Some(c) => format!("exit {c}"),
            None => {
                #[cfg(unix)]
                {
                    use std::os::unix::process::ExitStatusExt;
                    format!("signal {}", s.signal().unwrap_or(0))
                }
                #[cfg(not(unix))]
                {
                    "signal".to_string()
                }
            }
        },
    };
    let mut calls = Vec::new();
    let mut stderr = Vec::new();
    for line in out.stderr.split_inclusive(|b| *b == b'\n') {
        let text = String::from_utf8_lossy(line);
        if let Some(rest) = text.strip_prefix(LOG_PREFIX) {
            if let Some(c) = rest.trim().strip_prefix("calls ")
                && let Some((name, n)) = c.split_once('=')
                && let Ok(n) = n.trim().parse()
            {
                calls.push((name.to_string(), n));
            }
        } else {
            stderr.extend_from_slice(line);
        }
    }
    Ok(RunOutcome {
        exit,
        stdout: out.stdout,
        stderr,
        calls,
    })
}

/// Runs `binary` twice in the sandbox, plain and with `library` preloaded, and compares.
pub fn check_run(
    binary: &Path,
    library: &Path,
    args: &[String],
    stdin: Option<&str>,
    confinement: &Confinement,
) -> Result<PreloadComparison, RewriteError> {
    Ok(PreloadComparison {
        original: run_one(binary, None, args, stdin, confinement)?,
        preloaded: run_one(binary, Some(library), args, stdin, confinement)?,
    })
}

/// What the preload mode cannot do, for the result and the README.
pub fn limits() -> Vec<String> {
    [
        "x86-64 ELF programs only; the library does nothing when the size of the running \
         program differs from the analysed file",
        "functions shorter than 14 bytes stay in the original",
        "functions that use the program's own stdin, stdout or stderr objects are not supported",
        "output written by a replaced function goes through Rust's buffer, not the C library's, \
         so its order against the original's own output can differ when output is a pipe",
        "a program that makes its code pages unwritable beyond mprotect, or runs under another \
         loader, is left unchanged",
        "export again after accepting more functions, then build the preload library again",
    ]
    .iter()
    .map(|s| s.to_string())
    .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_launcher_preloads_next_to_itself() {
        let t = launcher_text("libx_preload.so");
        assert!(t.contains("LD_PRELOAD=\"$here/libx_preload.so"));
        assert!(t.contains("exec \"$@\""));
    }

    #[test]
    fn a_difference_names_the_first_thing_that_differs() {
        let run = |exit: &str, out: &str| RunOutcome {
            exit: exit.into(),
            stdout: out.as_bytes().to_vec(),
            stderr: Vec::new(),
            calls: Vec::new(),
        };
        let same = PreloadComparison {
            original: run("exit 0", "a"),
            preloaded: run("exit 0", "a"),
        };
        assert!(same.identical() && same.difference().is_none());
        let other = PreloadComparison {
            original: run("exit 0", "a"),
            preloaded: run("exit 0", "b"),
        };
        assert!(
            other
                .difference()
                .is_some_and(|d| d.starts_with("stdout differs"))
        );
    }
}
